const assert=require('node:assert/strict');
const {Game}=require('../dist/engine.js');
const Guide=require('../dist/guide.js');
const copy=g=>JSON.parse(JSON.stringify(g.s));
let g=new Game({count:4,humanCount:4});
let before=copy(g);assert(Guide.next(g).title.includes('门'));assert.deepEqual(g.s,before);
g.move(1);let result=Guide.impact(before,g.s,'move').join(' ');
assert(result.includes('新房间'));assert(result.includes('归零'));assert.equal(Guide.next(g).action,'end');
g.s.drawnOmen=true;g.s.omen=4;assert(Guide.next(g).text.includes('相等不会触发'));
g.p.controller='ai';assert.equal(Guide.next(g).action,null);assert(Guide.next(g).title.includes('AI'));
g.p.controller='human';g.startHaunt();assert(Guide.next(g).action.startsWith('task:'));
g.s.taskUsed=true;assert.equal(Guide.next(g).action,'end');
g.s.active=g.s.traitor;g.turnStart();assert(Guide.next(g).text.includes('叛徒'));
g.s.active=0;g.turnStart();g.summon('hero');
g.p.room=g.s.corpseRoom;assert.equal(Guide.next(g).action,'task:2');
g.s.carrier=g.p.id;g.p.room=g.s.burialRoom;assert.equal(Guide.next(g).action,'task:2');
assert(Guide.next(g).text.includes('仅仅走进房间不会获胜'));
g.s.taskUsed=true;assert.equal(Guide.next(g).action,null);
g.s.active=g.s.traitor;assert(Guide.next(g).title.includes('阻止'));
g.s.active=0;g.summon('traitor');g.turnStart();g.p.room=g.s.ghost.room;assert.equal(Guide.next(g).action,'attack:ghost');
g.s.attackUsed=true;assert.equal(Guide.next(g).action,'end');
before=copy(g);g.damage(g.p,1);assert(Guide.impact(before,g.s,'attack').some(s=>s.includes('轨移动')));
g.endGame('hero','测试结局');assert.equal(Guide.next(g).action,null);
console.log('Guide: exploration, card stop, omen comparison, AI observation, factions, burial, ghost, damage and terminal state passed; advice does not mutate game state.');
