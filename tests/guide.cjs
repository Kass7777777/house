const assert=require('node:assert/strict');
const {Game}=require('../dist/engine.js');
const Guide=require('../dist/guide.js');
const copy=g=>JSON.parse(JSON.stringify(g.s));
let g=new Game({count:4,humanCount:4});
let before=copy(g);assert(Guide.next(g).title.includes('门'));assert.deepEqual(g.s,before);
g.move(1);let result=Guide.impact(before,g.s,'move').join(' ');
assert(result.includes('新房间'));assert(result.includes('归零'));assert.equal(Guide.next(g).action,'end');
g.s.drawnOmen=true;g.s.omen=4;assert(Guide.next(g).text.includes('相等不会触发'));
g.p.controller='ai';assert.equal(Guide.next(g).action,null);assert(Guide.next(g).title.includes('AI'));
g.p.controller='human';g.startHaunt();assert(Guide.next(g).action.startsWith('task:'));
g.s.taskUsed=true;assert.equal(Guide.next(g).action,'end');
g.s.active=g.s.traitor;g.turnStart();assert(Guide.next(g).text.includes('叛徒'));
g.s.active=0;g.turnStart();g.summon('hero');
g.p.room=g.s.ghost.room;g.s.moves=0;
assert.notEqual(g.p.room,g.s.corpseRoom);
assert(Guide.next(g).text.includes('✧ 表示幽灵，并非遗骸位置'));
assert(Guide.next(g).text.includes(g.roomNow.name));
assert.equal(Guide.next(g).action,'end');
assert(Guide.next(g).focus.includes('移动力已用尽'));
g.p.room=g.s.corpseRoom;assert.equal(Guide.next(g).action,'task:2');
assert(Guide.next(g).focus.includes('移动力为 0'));
g.s.carrier=g.p.id;g.p.room=g.s.burialRoom;assert.equal(Guide.next(g).action,'task:2');
assert(Guide.next(g).text.includes('仅仅走进房间不会获胜'));
g.s.taskUsed=true;assert.equal(Guide.next(g).action,null);
g.s.active=g.s.traitor;assert(Guide.next(g).title.includes('阻止'));
g.s.active=0;g.summon('traitor');g.turnStart();g.p.room=g.s.ghost.room;assert.equal(Guide.next(g).action,'attack:ghost');
g.s.attackUsed=true;assert.equal(Guide.next(g).action,'end');
before=copy(g);g.damage(g.p,1);assert(Guide.impact(before,g.s,'attack').some(s=>s.includes('轨移动')));
g.endGame('hero','测试结局');assert.equal(Guide.next(g).action,null);
console.log('Guide: exploration, card stop, omen comparison, AI observation, factions, burial, ghost, damage and terminal state passed; advice does not mutate game state.');

const c=new Game({count:4,humanCount:4});
let state=copy(c);assert(Guide.cue(c).action.startsWith('move:'));assert.deepEqual(c.s,state);
c.s.moves=0;assert.equal(Guide.cue(c).action,'end');
c.startHaunt();c.s.active=c.s.players.find(p=>p.team==='hero').id;c.turnStart();c.summon('hero');c.s.taskUsed=false;c.s.moves=10;
let cue=Guide.cue(c);assert(cue.action.startsWith('move:')||cue.action.startsWith('room:'));
if(cue.action.startsWith('move:'))assert(c.exits()[Number(cue.action.split(':')[1])].open);
c.p.room=c.s.corpseRoom;c.s.moves=0;assert.equal(Guide.cue(c).action,'task:2');
c.p.controller='ai';assert.equal(Guide.cue(c).action,null);
console.log('Action cues: legal movement, exhausted movement, remains route, zero-move search and AI suppression passed.');

const once=new Game({count:4,humanCount:4});once.s.guide={enabled:true,lesson:3,learned:{}};
assert.equal(Guide.lessonKey(once),'move');once.s.guide.learned.move=true;
assert.equal(Guide.tutorial(once),null);once.s.moves=0;
assert.equal(Guide.lessonKey(once),'end');assert(Guide.tutorial(once));once.s.guide.learned.end=true;
assert.equal(Guide.tutorial(once),null);once.s.drawnOmen=true;
assert.equal(Guide.lessonKey(once),'end-omen');assert(Guide.tutorial(once));
once.s.guide.learned['end-omen']=true;
const resumed=new Game({},copy(once));assert.equal(Guide.tutorial(resumed),null);
resumed.startHaunt();resumed.s.taskUsed=false;assert(Guide.tutorial(resumed));
assert(Guide.lessonKey(resumed).startsWith('ritual-'));
console.log('One-time tutorials: learned steps suppressed, new omen/ritual contexts retained, progress survives save restoration.');
